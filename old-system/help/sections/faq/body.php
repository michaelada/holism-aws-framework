                    <li>Select the <strong>All Members Ever</strong> filter on the left. <strong>Note; </strong>
                        if you do not have this filter then
                        add it by following the steps outlined above
                        for <strong>M-2 - What are Membership Filters and how do I add them</strong>.
                    </li>
                    <li>Click on the column <strong>Date Last Renewed</strong> in the table to see the most
                        recently renewed members records.
                    </li>
                    <li>If there are any that are marked as member status <strong>Elapsed</strong> but were
                        recently
                        renewed,
                        then edit the record, change their member
                        status to <strong>Active</strong> and make sure you edit their <strong>Valid Until</strong>
                        field to
                        set it to the
                        correct date.
                    </li>
                </ul>

