                    Membership Types and make sure
                    that all of your Membership Types have the <strong>Valid Until</strong> field set to a
                    correct date in the future.
                    This can typically be set incorrectly if you are moving from one years membership to the
                    next, and you forget to
                    update your membership types as part of this process.
                </p>
                <p>
                    For anyone that paid for membership but is now marked as elapsed because of this, you can
                    fix their membership records
                    by following these steps:</p>
