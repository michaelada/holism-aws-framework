                    This is possible, however you need to learn a few rules about how to do this, as follows
                    (note:
                    if you are already familiar with HTML then this should be straightforward for you):</p>
                <ul>
                    <li><strong>Add a new line</strong> - you can add a line break within the text using the
                        following tag &lt;br&gt;
                    </li>
                    <li><strong>Displaying Text In Bold</strong> - if you would like a piece of text to be
                        displayed
                        in bold then
                        you need to surround it with the opening tag <strong>&lt;strong&gt;</strong> and the
                        closing
                        tag <strong>&lt;/strong&gt;</strong>.
                        So for example if you would like to have a section title called
                        <strong>Introduction</strong> in bold on a line by itself then you would
                        enter the following text in the Terms and Conditions section.<br><br>
                        <strong>&lt;strong&gt;</strong>Introduction<strong>&lt;/strong&gt;&lt;br&gt;</strong>This
                        is the
                        section text etc ...<br><br>
                        which would end up being displayed as follows:
                        <hr>
                        <p><strong>Introduction</strong><br>This is the section text etc ...<br>
                            <hr>
                        </p>
                    </li>
                    <li><strong>Add a clickable link</strong> - you can add a web address and make it clickable
                        by surrounding it with special tags called "anchor tags". So for example if you would
                        like to include a clickable link to the web address
                        <strong>https://www.itsps.club/avril</strong>
                        then you need to enter the following code.<br><br>
                        <p class="medium indent code">
                            <font color="red">&lt;a</font>
                            <font color="blue">href=</font>
                            <font color="green">'https://www.itsps.club/avril'</font>
                            <font color="blue">target=</font>
                            <font color="green">'_blank'</font>
                            <font color="red">&gt;</font>https://www.itsps.club/avril<font color="red">&lt;/a&gt;</font>
                        </p>
                        <p class="medium indent code">So if we look at this the definition <font color="red">&lt;a
                            </font>
                            <font color="blue">href=</font>
                            <font color="green">'full web address'</font>
                            <font color="blue">target=</font>
                            <font color="green">'_blank'</font>
                            <font color="red">&gt;</font>
                            <font color="green">full web address</font>
                            <font color="red">&lt;/a&gt;</font>
                            it is made up of the following parts:
                        </p>
                        <ul>
                            <li class="medium indent code"><strong>
                                    <font color="red">&lt;a</font> attributes
                                    <font color="red">&gt;</font> display text <font color="red">&lt;/a</font>
                                    <font color="red">&gt;</font>
                                </strong>
