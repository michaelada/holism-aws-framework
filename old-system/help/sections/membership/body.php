        <h1>
            <a name="membership-types">Membership Types</a>
        </h1>
        <p>A membership type is a particular type of membership that you support within your organisation.
            An example of a Membership Type might be an <b>Adult Membership</b>, a <b>Child Membership</b>, or a
            <b>Family
                Membership</b>. The actual membership types
            used in a specific organisation will vary. Using different membership Types allows you to
            define
            different membership criteria such as the membership fee, membership terms and conditions,
            different payment methods, and so forth.
        </p>
        <p>To add a Membership Type, or edit an existing one you should click on the <b>Membership Types</b>
        sub menu on the left hand side of the <strong>Memberships</strong> area.
            This will show you something like the figure below, where the membership types are listed.
        </p>
        <div class="figure-holder">
            <img class="helpfigure" width="797"
                    src="images/membership-3.png">
        </div>
        <p class="figure-title">Memberships -> Membership Types</p>

        <p>When you click on the <span
                    class='normalbutton editentry'>Add Membership Type</span> button you will be presented with
            a
            list of fields to fill
            out for
            the new Membership Type you wish to add.
            The figure below shows an example screenshot for a new membership type being added.</p>

        <div class="figure-holder">
            <img class="helpfigure" width="797"
                    src="images/membership-8.png">
        </div>
        <div class="figure-holder">
            <img class="helpfigure" width="400"
                    src="images/membership-8a.png">
        </div>
        <p class="figure-title">Adding New Membership Type</p>

        <p>The different fields in a membership type are explained in more detail below.</p>
        <ul class="sublist">
            <li><span class='highlight title'>Name</span> - You should enter a suitable name for this
                membership
                type. This is the name that will be displayed to your members on your Organisations public
                online entries/
                payments Page.
            </li>
            <li><span class='highlight title'>Description</span> - You should enter a suitable description
                for this
                membership type. Again this description will be displayed to your members on your
                Organisations public
                online entries/ payments Page.
            </li>
            <li><span class='highlight title'>Membership Form</span> - You should select from the drop down
                list the
                Membership Form to use for this membership type. Note: We recommend that you use the same
                Membership
                form for all membership types as
                this ensures that the same fields of information will be provided to your central database.
                There
                are of course exceptions to this, for example if you have a Child Membership and an Adult
                Membership
                where possibly a child membership requires
                different fields in the membership form than the Adult.
            </li>
            <li><span class='highlight title'>Add Mem, Number To Form</span> - If this Membership Type is
                for
                existing members to renew their membership then you can set this option to Yes and then the
                Membership Form will be updated to include a Membership Number
                field, and when the member fills out their membership number it can be used to automatically
                populate fields within the Membership form by pulling them from the central organisation
                database
                (asuming
                the details are already stored there). If, on the other hand this
                Membership Type is for new members or if your organisation does not use Membership Numbers then
                set
                this to
                No.
            </li>
            <li><span class='highlight title'>Membership Status</span> - This defaults to Open, however you
                can
                close membership for this type by setting this to <b>Closed</b>.
                When you set this to Closed, this Membership Type is listed on your Organisations public
                online entries/
                payments Page, but it is shown to your members/ visitors as <b>Closed for Applications</b>.
            </li>
            <li><span class='highlight title'>Is Rolling Membership</span> - There are two approaches available when it
                comes to determining how long a membership lasts for. The traditional approach is where it is based
                on a fixed period, e.g. annual membership up to 31st December. The alternative approach is where it
                is rolling based on the point at which the person pays/ renews.
                <ul>
                    <li><strong>Is Rolling Membership = No</strong> - select this option for memberships that end on a specific
                        date and then set the actual date in the <span class='highlight title'>Valid Until</span> field.</li>
                    <li><strong>Is Rolling Membership = Yes</strong> - select this option where the membership is valid
                    for a fixed number of months, from the date in which the person pays for this membership. For example
                    if you want to offer 12 month rolling membership then set this field to Yes, and in the
                        <span class='highlight title'>Number Of Months</span> field that is displayed enter 12.</li>
                </ul>
            </li>
            <li><span class='highlight title'>Valid Until</span> - If <strong>Is Rolling Membership = No</strong>
                then you should set this field to the date that
                this
                membership type is valid until. So for example if you are adding a new membership type
                called
                <b>2025 Membership Renewal</b> then you would set this to 31st December 2025 which would
                mean that
                anyone renewing their membership would be marked as being paid up until this date.
                <strong>Note: </strong> every night at midnight the system automatically changes the status
                of any <strong>Active</strong> members to <strong>Elapsed</strong> if their <strong>Valid
                    Until</strong>
                date is in the past so it is important to set this date correctly.
                <br>If on the other hand <strong>Is Rolling Membership = Yes</strong> then the system will set this automatically
                when the person pays their membership based on the  <span class='highlight title'>Number Of Months</span>
                from that exact point in time.
            </li>
            <li><span class='highlight title'>Automatically Approve Application</span> - by default when a
                new
                Membership Application is submitted to your organisation, the members details within your
                central
                membership database are marked
                as status <b>Pending</b>, however if you set this field to Yes then the member will be
                automatically
                marked as <b>Active</b>.
                This option might typically be set to No for New Membership Applications where the member is
                marked
                as status <b>Pending</b> until someone within the committee has had a chance to review the
                application and then if approved, manually change the membership record to
                <strong>Active</strong>.
            </li>
            <li><span class='highlight title'>Restrict With Pass Code</span> - You can set this field to Yes
                if you
                want to restrict access to this membership type by password/ passcode.
                If this option is used then only people who know the passcode can actually submit an
                application
                for this membership type. When you set this to Yes, the field below <strong>Pass Code To
                    Use</strong> will be displayed where you enter the actual passcode that people must enter
                before they
                can submit this membership type.
            </li>
            <li><span class='highlight title'>Pass Code To Use</span> - This field is only displayed if the
                previous
                field <strong>Restrict With Pass Code</strong> is set to Yes. When used you should enter a
                pin/
                password to apply
                to this membership type. Then when someone tries to submit a membership application for
                this
                membership type, they will not be allowed to complete the operation without entering the
                correct
                passcode, set here.
            </li>
            <li><span class='highlight title'>Add Member Labels</span> - Optionally you can select those labels
                you wish to
                automatically add to any member who uses this membership type. All labels are defined under
                Settings -> Labels.
                If you select a label here, then any member that applies using this membership type will
                automatically
                be tagged with the selected label. Labels can be used within your <strong>Members</strong>
                central database to create Filters e.g. to show all members with a specific label assigned.
            </li>

            <li><span class='highlight title'>Show/ Use Gender</span> - By default the membership application
                form always
                includes a Gender field. Set this to No if you wish to hide the Gender field in the membership
                form for this membership type.
                When this is set to No then you must select the <strong>Default Gender</strong> to use.
            </li>

            <li><span class='highlight title'>Show/ Use Date Of Birth</span> - By default the membership
                application form always
                includes a Date Of Birth field. Set this to No if you wish to hide the Date Of Birth field in
                the membership form for this membership type.

            </li>

            <li><span class='highlight title'>Show/ Use Contact Name</span> - By default the membership
                application form always
                includes a Contact Name field. Set this to No if you wish to hide the Contact Name field in the
                membership form for this membership type.

            </li>
            <li><span class='highlight title'>Show/ Use Contact Address</span> - By default the membership
                application form always
                includes a Contact Address field. Set this to No if you wish to hide the Contact Address field in the
                membership form for this membership type.

            </li>
            <li><span class='highlight title'>Show/ Use Contact Mobile</span> - By default the membership
                application form always
                includes a Contact Mobile number field. Set this to No if you wish to hide the Contact Mobile field in the
                membership form for this membership type.

            </li>

            <li><span class='highlight title'>Membership Fee</span> - You should set this to the fee that
                the person
                must pay when submitting a membership application for this membership type.
            </li>
            <li><span class='highlight title'>Allow Pay By Credit/ Debit Card</span> - Set this to Yes to
                enable the
                choice to pay by credit/ debit card. Note: If an organisation is not activated for Credit/ Debit
                Card
                payments then this option will not be displayed.
            </li>
            <li><span class='highlight title'>Handling Fee Included</span> - If Allow Pay By Credit/ Debit
                Card is
                set to Yes then you should indicate here whether the Credit/ Debit Card Handling Fee is
                included in
                the Membership Fee (set to Yes), or
                if the Credit/ Debit Card Handling Fee is added on top of the Membership Fee (set to No)
            </li>
            <li><span class='highlight title'>Allow Pay By Cheque/ Offline</span> - You may also give people
                the
                option to pay by Cheque or offline using bank transfer by setting this to Yes, otherwise set
                it to
                No.
            </li>
            <li><span class='highlight title'>Cheque/ Offline Payment Instructions</span> - If <b>Allow Pay
                    By
                    Cheque/ Offline</b> is set to Yes then you should provide a description of
                how a person should make the payment. For example, who do they make the
                cheque
                payable to, where is the cheque sent to. Or if bank transfer is allowed then provide
                details of the IBAN that the person can use to make the payment. The text that is
                entered
                here will be automatically included in the confirmation email sent to the person
                once they
                have checked out using the "Cheque/ Offline" option.
            </li>

            <li><span class='highlight title'>Restrict to People Born After</span> - Set this to Yes
                if you would like to apply an age restriction to people who can apply for this membership type
                where they must be younger than a specific age.
                When you set this to Yes you will see another field called <strong>Born After This Date</strong>
                displayed.
                This field is used to set the date after which people must be born to be able to become a member
                of this type
                (i.e. for restricting people under a specific age). Note: if you use this option,
                then you should make sure that the <strong>Show/ Use Date Of Birth</strong> field
                is set to Yes.
            </li>

            <li><span class='highlight title'>Restrict to People Born Before</span> - Set this to Yes
                if you would like to apply an age restriction to people who can apply for this membership type
                where
                they must be older than a specific age.
                When you set this to Yes you will see another field called <strong>Born Before This
                    Date</strong> displayed.
                This field is used to set the date before which people must be born to be able to become a
                member
                of this type (i.e. for restricting to people over a specific age). Note: if you use this option,
                then you should make sure that the <strong>Show/ Use Date Of Birth</strong> field
                is set to Yes.
            </li>
            <li><span class='highlight field label'>Add Message To Confirmation Email</span> -
                If you want to add an extra message to the confirmation emails that get sent to
                people who sign up using this membership type then set this to Yes and then in the
                <strong>Confirmation Email Message</strong> field that is displayed type in the
                text that you would like to appear on the confirmation email.
            </li>

            <li><span class='highlight title'>Use Terms And Conditions</span> - If you would like to specify
                terms
                and conditions in the Membership Application form then set this to Yes.
            </li>
            <li><span class='highlight title'>Terms And Conditions</span> - If <b>Use Terms And
                    Conditions</b> is
                set to Yes then you must enter the actual terms and conditions text here that will be
                displayed on
                the Membership Application form.
                To read more about how to add some simplified formatting to the text here click
