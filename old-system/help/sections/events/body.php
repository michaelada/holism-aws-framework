<div class='subsection' id='events-whatisit'>
    <h1>
        <a name="events-whatisit">Events: What is an event</a>
    </h1>
    <p>An event is any activity for which you would like to allow people to take part.
        Examples of events in the context of
        ItsPlainSailing might be:</p>


    <ul class="help">
        <li><span class='highlight title'>Competition Day</span> - your are
            organising a day of competitions and you would like to set it up
            so that people can enter online through your website
        </li>
        <li><span class='highlight title'>Training Sessions</span> - you
            are organising special training and you need your members to
            apply online to attend the training.
        </li>
        <li><span class='highlight title'>Camp Week</span> - you are running
            a camp week and again you would like all members to be able to
            apply to attend camp online.
        </li>
        <li><span class='highlight title'>Club BBQ</span> - you plan
            to have a yearly BBQ for all members and you want to allow people
            to buy tickets online.
        </li>
        <li><span class='highlight title'>Ticket event</span> - you are running a
            ticketed event where people can book tickets online, the system then issues
            individual tickets to people (with QR Codes), and then we provide an iPhone
            App that you, as event organiser can use to scan tickets as people enter your event.
        </li>
        <li><span class='highlight title'>Other Activities</span> - the
            system is flexible allowing you to define a variety of events that
            suit your particular organisations activities.
        </li>
    </ul>

    <p>The figure below provides a high level overview of how it works. Basically, you as administrator of
        your
        organisations account can set up events with specific activities using application forms you have
        designed, and
        everything you set up will be automatically displayed online on your organisations public web page
        for people to
        enter and pay.</p>
