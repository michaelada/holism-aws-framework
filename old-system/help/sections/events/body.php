        <ul class="help">
            <li><span class='highlight title'>Different Age Categories</span> -
                So within your event you are taking entries for different age
                categories, e.g. Under 12s, Under 14's and Under 16s.
            </li>
            <li><span class='highlight title'>Different Competences</span> -
                Within your event you are taking entries for different standards,
                e.g. Junior, Intermediate, Pairs.
            </li>
            <li><span class='highlight title'>Different categories of Tickets</span>
                - Maybe you are organising an event with different ticket
                categories, e.g. Child, Adult, Family.
            </li>
            <li><span class='highlight title'>Other</span> - the system is
                flexible allowing you to define a variety of categories that suit
                your particular organisations event

        </ul>
    </div>
