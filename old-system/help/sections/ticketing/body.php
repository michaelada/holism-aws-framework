        <h1>
            <a name="ticketing-howitworks">Ticketing: How It Works</a>
        </h1>
        <p>With this functionality you can run events and have ItsPlainSailing manage the issuing of tickets
            and controlling access to your event with our custom QR Code scanning app that can be used to
            check all tickets on entry to your event ensuring only people with valid tickets can enter.
        </p>


        <ul class="help">
            <li><span class='highlight title'>Easy To Set Up</span> - you set up your event as you
                would, like any other event in ItsPlainSailing, and then to enable ticketing you just set the
                <strong>Generate Electronic Tickets</strong> field on the event to <strong>Yes</strong>.
            </li>
            <li><span class='highlight title'>Automatically Generates Tickets</span> - once enabled, the system
                will generate electronic tickets for your event and automatically email them to people whenever
                they make a booking.
            </li>
            <li><span class='highlight title'>Customise Your Tickets</span> - using the ticket settings
                section you can edit the text content that is printed on the tickets to personalise them for
                each event.
            </li>
            <li><span class='highlight title'>Scanning App</span> - Each generated ticket includes a unique
                QR Code and we provide a Scanning App (no additional charge) which you install on your smart
                phone and use to validate each ticket as people enter your event.
            </li>
            <li><span class='highlight title'>Ticketing Dashboard</span> - you can track all tickets, issued
                and scanned, in realtime as people are entering your event, or afterwards to better understand
                how your event was attended.
            </li>

        </ul>

        <p>The figure below highlights the <strong>Generate Electronic Tickets</strong> field on the Edit Event Details page.
            Simply set this field to <strong>Yes</strong> and the system will automatically generate electronic tickets for this
            event and email them to the people making the bookings.
        </p>
