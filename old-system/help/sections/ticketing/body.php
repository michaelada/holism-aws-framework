        <h1>
            <a name="ticketing-usingapp">Using the App</a>
        </h1>
        <p>The steps involved in using the App are relatively straightforward. You login into the App using the
            Access Code for the event, and the password if one is set. You enter your name, and your location at
            the event, and then you simply scan and approve the tickets as people present them to you at the event.</p>

        <h3>Logging In To App</h3>
        <p>When you first launch the app you will be presented with the screen below where you will be prompted to
            enter the <strong>Access Code</strong> for the event that you wish to scan the tickets.</p>
        <p>The access code is divided into two parts, enter the first part in the box on the left, and the second
        part in the box on the right.</p>
        <p>If the event organiser has added a password to the event, then you will be prompted to enter it.</p>
        <p>The last step in logging in is to provide your name and location, e.g, if there are multiple entry points
        to your event, then just type the name of the entry point you are located at and where you will be scanning tickets from, 
            e.g. front gate, back gate etc. </p>
