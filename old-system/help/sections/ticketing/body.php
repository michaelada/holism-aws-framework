            </li>
            <li><span class='highlight title'>(E) Scanner Password</span> - you can add an extra password that
                must be known and entered by people using the Scanning App at the event itself.
                Note: the person or persons scanning people into your event must use the access code when logging
                into the App on their phone. If you set a password here, then they will also be required to
                specify it when using the Scanner App (See logging in to Scanner App below).
            </li>

            <li><span class='highlight title'>(F) Settings Per Competition/ Activity/ Ticket Types </span> - as you
