        <h3>Multi Scan Tickets</h3>
        <p>The default behaviour is that once a ticket is scanned at an event, then it cannot be rescanned (i.e. used a second time).
            However it is also possible to set up your event and allow specific ticket types to be scanned multiple times.</p>
        <p>For multi-use tickets, when they are scanned on the App, you are presented with the option to indicate
            how many scans you would like to record against the ticket at that point in time. For example, if a Ticket Type
        supports up to 5 scans, and two people are being scanned in with the ticket at a specific point in time, then
        you would set number of Scans to 2, and then click the <strong>Confirm Ticket Scan</strong> button. </p>
