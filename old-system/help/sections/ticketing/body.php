        <p>On the <strong>Settings</strong> page you can see the following:</p>
        <ul class="help">
            <li><span class='highlight title'>(A) Access Code</span> - the unique access code for this event that is needed by anyone who
            will be using the <strong>Scanner App</strong> to check tickets as people enter your event.</li>
            <li><span class='highlight title'>(B) Event Ticket Information</span> - optionally you can enter specific event details
                    here. Whatever you type here will be included in the Event Information section of the Tickets that
                are generated for this event. Remember you can see what the ticket looks like by clicking the preview
                menu option on the left.
            </li>
            <li><span class='highlight title'>(C) Venue</span> - optionally, if you would like the name of the venue to be
                printed on the ticket then add it here. Note: this field may not be needed if you have already named the venue
                in the Event name, or you have already explained the venue in the Event Ticket Information field, it is your choice.
            </li>
            <li><span class='highlight title'>(D) Event Start and End Time</span> - you can also optionally specify a
                start time, or an end time, or both, for your event, which will be printed on the ticket, otherwise it will
