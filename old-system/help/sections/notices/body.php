            <strong>Notice Boards</strong>. If you click on this menu you will be presented with 
        a set of screens that you can use to customise your ItsPlainSailing Public Web Page with
        Notice Boards and add / remove notices from these boards. The figure below shows an example
        of a set of notice boards, one called <strong>Club Notices</strong> and one called 
        <strong>Youth Notices</strong>. The <strong>Club Notices</strong> is shown as selected and
    it has 2 notices displayed one about memberships being due and one about the upcoming AGM.  </p>
