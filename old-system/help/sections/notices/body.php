        <div class="figure-holder">
            <img class="helpfigure" width="864" src="images/settings-notices-2.png"/>
        </div>
        <p class="figure-title">Notice Boards Administration Area</p>

        <p> From here you have full control over what gets displayed within your pubic web pages 
            notice boards area:</p>

        <ul>
            <li><span class='highlight title'>Show This Section</span> - Firstly if you do not wish to 
            use this Notice Boards functionality and would like to hide it from visitors to your Public 
            Page then simply edit the <strong>Show This Section</strong> field and change it to 
            <strong>No</strong>.</li>

            <li><span class='highlight title'>Button Display Text</span> - As with other areas 
            of the ItsPlainSailing public web page you can edit the button text for the notice boards
            as you wish, note by default the button text is <strong>Notices</strong>.</li>

            <li><span class='highlight title'>Button Description</span> - you can also edit this field to change
            the displayed text that appears on your Public Page to the right hand side of the button.</li>

            <li><span class='highlight title'>Section Title</span> - when the user scrolls down to the 
            Notice Boards section on their Public Web Page where the notices are displayed you can use this field to change the title 
            of the section (currently defaults to <strong>Notice Boards</strong>).</li>

            <li><span class='highlight title'>Section Description</span> - when the user scrolls down to the 
            Notice Boards section on their Public Web Page where the notices are displayed you can use this field to change the 
            description text that is displayed under the section title (currently defaults to <strong>All our notices are displayed below</strong>).</li>
            
            <li><span class='highlight title'>Adding Notice Boards</span> - With the section titled 
            <strong>Edit Content of Notice Boards</strong> you will see a list of the existing Notice Boards
            that have already been added to your Public Page, and you will see an 
            <span class="normalbutton">Add Notice Board</span> button above the table on the right which you can use 
            to add more notice boards. Click <a href="#notices-addboard">Adding Notice Boards</a> to read more about 
            how to add and edit your Notice Boards.</li>
            <li><span class='highlight title'>Adding Notices</span> - you can click the <span class="normalbutton">Edit</span> button 
            to add notices to an existing notice board and to 
            change the text and/ or remove existing notices.  
            Click <a href="#notices-addnotice">Adding Notices</a> to read more about 
            how to add and edit specific notices.</li>
        </ul>
        
    </div>


    <div class='subsection' id='notices-addboard'>
        <h1>
            <a name="notices-addboard">Adding Notice Boards</a>
        </h1>
        <p>To add a new Notice Board to your Public Web Page click the <span class="normalbutton">Add Notice Board</span>
         button above the table on the right and you will be presented with the form below, which you should fill out and then 
         click the <span class="normalbutton save">Add</span> button.</p>
         <p>Remember that whatever you type into the name and description fields is what will be displayed 
            to people on your Public web page.
         </p>
         <div class="figure-holder">
            <img class="helpfigure" width="864" src="images/settings-notices-3.png"/>
        </div>
        <p class="figure-title">Add Notice Board Form</p>
        
    </div>

    <div class='subsection' id='notices-addnotice'>
        <h1>
            <a name="notices-addnotice">Adding Notices</a>
        </h1>
        <p>To add notices to an existing Notice Board you should first click the <span class="normalbutton">Edit</span> 
        button to the right of the specific Notice Board, and then click the <span class="normalbutton">Add New Notice</span> button above the table of notices on the right.
    When you do you will be presented with the following form:</p>
        <div class="figure-holder">
            <img class="helpfigure" width="864" src="images/settings-notices-4.png"/>
        </div>
        <p class="figure-title">Add Notice Form</p>
        <p>The fields on this form are as follows:</p>
        <ul>
            <li><span class='highlight title'>Title</span> - Enter here the title of the notice that you want to display.</li>

            <li><span class='highlight title'>Notice Link</span> - as an option you can add a button to this notice which, when clicked, 
            brings the user to a specific web address. If you wish to use this option then enter the web address 
            that you want people to jump to here.</li>

            <li><span class='highlight title'>Notice Details</span> - Enter the details of the notice that you want to display.</li>

            <li><span class='highlight title'>Link Text</span> - this field works in conjunction with the <strong>Notice Link</strong> field.
            If you add a notice link then you can enter here the text you want to appear on the Button that
            is displayed at the bottom of the notice.
            </li>
            <li><span class='highlight title'>Show Publicly</span> - If you want to temporarily hide this notice you can set this to <strong>No</strong>,
            otherwise leave it as <strong>Yes</strong>.</li>
        </ul>

