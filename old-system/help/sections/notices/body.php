    <div class='subsection' id='notices-automatic'>
        <h1>
            <a name="notices-automatic">Automatic Notices</a>
        </h1>
        <p>If the notice boards section is not hidden on your Public Page then the system
            also adds some automatic notices as follows:</p>
        <ul>
            <li><span class='highlight title'>Event Entries Opening Soon</span> - if the entries in an event are opening soon then an automatic 
            notice is added to the notice boards to indicate this.</li>
            <li><span class='highlight title'>Event Entries Closing Soon</span> - if the entries in an event are closing soon then an automatic 
            notice is added to the notice boards to indicate this.</li>
        </ul>
