            <a name="shop-deliveryoptions">Setting Up Different Delivery Options</a>
        </h1>
        <p>
        <p> If your merchandise has different delivery options and associated delivery fees to apply then
            you need to set these up first.
            To do this you should log into your ItsPlainSailing account, select the <strong>Shop</strong> menu
            option
            and then click on <strong>Delivery Options</strong> on the left. An example of the type of screen
            you will see is shown below.
        </p>

        <div class="figure-holder">
            <img class="helpfigure" style="width:697px"
                    src="images/shop-images-3.png">
        </div>
        <p class="figure-title">Delivery Options</p>

        <p>From here you can edit existing delivery options (see <font color='orange'>2</font>) and add new ones
            (see <font color='orange'>1</font>).</p>

        <h4>Adding a Delivery Option</h4>
        <p>When it comes to delivery options they are re-usable across different types of merchandise, so for
            example if you have two types of merchandise that
            have a postal delivery option with a fee of 3.00 <?php echo isset($currency) ? $currency : ""; ?>
            then you only need to set this up once and
            then you can use it for each of your different
            merchandise types that offer postal delivery at
            3.00 <?php echo isset($currency) ? $currency : ""; ?>. To add a new Delivery Option click the
            <span
                    class='normalbutton editentry'>Add New Delivery Option</span> button and you will be
            presented with the screen below.
        </p>

        <div class="figure-holder">
            <img class="helpfigure" style="width:697px"
                    src="images/shop-images-4.png">
        </div>
        <p class="figure-title">Add New Delivery Option</p>

        <p>For each delivery option you should give it a name and description. The text you enter here will be
            displayed to the user
            when they are selecting their options to buy the merchandise so keep this in mind and make the text
            as meaningful as possible.
            Then you should select the Category for this delivery option where the 4 different categories
            supported are as follows:</p>
        <ul>
            <li><span class='highlight title'>Pick Up</span> - this category is used if you are allowing the
                item to be picked up
                at a specific address/ location without any fee. If you select this category then please make
                sure that the description field
                for this delivery option explains where the item can be picked up.
            </li>
            <li><span class='highlight title'>Free Delivery</span> - this category is used if you are allowing
                the
                item to be delivered to the persons address free of charge. If you select this category then
                when
                a person
                is checking out they will be automatically prompted to provide the delivery address that they
                would like
                to use.
            </li>
            <li><span class='highlight title'>Fee Per Item</span> - this category is used if you charge a fee
                per item of this
                type, e.g. 1.50 <?php echo isset($currency) ? $currency : ""; ?> per item purchased. If you
                select this category then the screen displays
                a <strong>Delivery Fee</strong>
                field where you must enter the actual fee to charge in this case. Also, if you select this
                category then when a person
                is checking out they will be automatically prompted to provide a delivery address. If you set
                this up as an option and
                use it for a specific merchandise type (e.g. Club T-Shirt), then if a person orders 3 T-Shirts,
                they will be charged 3 times
                the Delivery Fee (i.e. a fee per item of this type ordered).
            </li>
            <li><span class='highlight title'>One Delivery Fee For All Items Of This Type</span> - this category
                is used if you charge one delivery fee
                for all items of this type, e.g. 1.50 <?php echo isset($currency) ? $currency : ""; ?>. If you
                select this category then the screen displays
                a <strong>Delivery Fee</strong>
                field where you must enter the actual fee to charge in this case. Also, if you select this
                category then when a person
                is checking out they will be automatically prompted to provide a delivery address. If you set
                this up as an option and
                use it for a specific merchandise type (e.g. Club T-Shirt), then if a person orders 1, 2 or 3
                T-Shirts
                then the delivery fee is still the same, so quantity does not matter in this case.
            </li>
        </ul>

