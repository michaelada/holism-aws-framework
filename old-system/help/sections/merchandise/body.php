        <p>The different fields in this form are as follows</p>
        <ul class="sublist">
            <li><span class='highlight title'>Name</span> - You should enter a suitable name for this
                particular option e.g. Small, Medium ... This is the name that will be displayed to people
                on your Organisations public
                online entries/
                payments Page.
            </li>
            <li><span class='highlight title'>Description</span> - You should enter a suitable description
                for this
                option here.
            </li>

            <li><span class='highlight title'>Apply Limit</span> - If you have limited availability of stock for
                this
                option then you can set this to Yes and then enter the current number of items of this type that
