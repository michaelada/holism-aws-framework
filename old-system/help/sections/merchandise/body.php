        <p>To add or edit the sizes/ options on a specific Merchandise Type you should click the <span
                    class='normalbutton events'>Edit</span> button
            for the merchandise type in question and then click the <span
                    class='normalbutton events'>Add New Size/Option</span> button which will present a form as shown
