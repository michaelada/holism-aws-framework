        <h4>Add a new Merchandise Type</h4>
        <p>
            To add a new type of merchandise click the <span
                    class='normalbutton editentry'>Add New Merchandise Type</span> button and you will be
            presented with the screen below.
        </p>

        <div class="figure-holder">
            <img class="helpfigure" style="width:697px"
                    src="images/shop-images-6.png">
        </div>
        <p class="figure-title">Add New Merchandise Type</p>


        <p>The different fields in a merchandise type are explained in more detail below.</p>
        <ul class="sublist">
            <li><span class='highlight title'>Name</span> - You should enter a suitable name for this
                merchandise
                type. This is the name that will be displayed on your Organisations public
                online entries/
                payments Page.
            </li>
            <li><span class='highlight title'>Description</span> - You should enter a suitable description
                for this
                merchandise type. Again this description will be displayed on your
                Organisations public
                online entries/ payments Page.
            </li>

            <li><span class='highlight title'>Available In Stock</span> - You can set this to No to mark that
                this item is not in stock and it will not be available on your public online page, otherwise
                leave it as Yes.
            </li>

            <li><span class='highlight title'>Has Delivery Options</span> - Set this to yes if this particular
                piece of merchandise has delivery options that the person can choose from.
                If this is set to Yes then two additional fields are displayed which you must fill out (see
                below).
                <strong>Note:</strong> if there is only one option for this item, e.g. it has to be picked up
                from
                a committee member, then just put this information in the <strong>Description</strong> field
                mentioned
                above, and then leave <strong>Has Delivery Options</strong> set to No.
            </li>

            <li><span class='highlight title'>Delivery Description</span> - This field is only displayed
                when <strong>Has Delivery Options</strong> is set to Yes. Here you should enter
                some meaningful text which explains the delivery option choices that are available for this
                merchandise type keeping in mind that this text will be displayed to people when they
                select
                this item for ordering.
            </li>
            <li><span class='highlight title'>Available Delivery Options</span> - This field is only displayed
                when <strong>Has Delivery Options</strong> set to Yes. Here you can click on the drop down list/
                box
                and select one or more of the delivery options that are available to people ordering this
                merchandise
                type. Note: the list will be populated with the names of the Delivery Options that you have
                previously
                set up under Shop -> Delivery Options.
            </li>

            <li><span class='highlight title'>Images To Use</span> - Here you can click on the drop down list/
                box
                and select one or more of the Merchandise Images that will be displayed with this merchandise
                type on your public online page. Note: the list will be populated with the names of the
                Merchandise Images that you have previously set up under Shop -> Merchandise Images.
            </li>

            <li><span class='highlight field label'>Allowed Payment Method</span>
                - Here you can select the payment methods supported for this merchandise type, you can allow
                your
                members to pay by credit/ debit card, by cheque/ offline or by both.
                <span class='highlight'>Note:</span> if your organisations
                account is not activated for credit/ debit card payments then only the
                <strong>Pay By Cheque / Offline</strong> option will be available.

            </li>

            <li><span class='highlight field label'>Handling Fee Included</span>
                - If you choose payment by credit/ debit card
                then you will also have the option to indicate if the Credit/ Debit Card
                Handling charge is included in the fee or if it is excluded
                (i.e. should be added on top of the fee). For more
                information on credit/ debit card handling fees goto
                <a class='internal-ref' href='#payments-handlingcharges'>Handling
                    Fees</a>.


            </li>

            <li><span class='highlight field label'>Cheque/ Offline Payment Instructions</span>
                - If you choose payment by Cheque / Offline then you should provide a description of
                how a person should make the payment. For example, who do they make the
                cheque
                payable to, where is the cheque sent to. Or if bank transfer is allowed then provide
                details of the IBAN that the person can use to make the payment. The text that is
                entered
                here will be automatically included in the confirmation email sent to the person
                once they
                have checked out.
            </li>


            <li><span class='highlight title'>Use Terms And Conditions</span> - If you would like to specify
                terms
                and conditions then set this to Yes.
            </li>
            <li><span class='highlight title'>Terms And Conditions</span> - If <b>Use Terms And
                    Conditions</b> is
                set to Yes then you must enter the actual terms and conditions text here that will
                apply to people ordering this merchandise type.
                To read more about how to add some simplified formatting to the text here click
                <a href="#more-faq-13">Here</a>.
            </li>

            <li><span class='highlight field label'>Add Message To Confirmation Email</span> -
                If you want to add an extra message to the confirmation emails that get sent to
                people purchasing this merchandise then set this to Yes and then in the
                <strong>Confirmation Email Message</strong> field that is displayed type in the
                text that you would like to appear on the confirmation email.
            </li>
        </ul>
        <p>When you have filled out the required
            information you then click the <span class='normalbutton save'>Add</span>
            button to create this new Merchandise Type, however please note that you are not finished yet as you
            have to add one or more Sizes/ Options (see below for help on how to do this).</p>

