            When you have your images and relevant delivery options setup then you can start adding your actual
            <strong>Merchandise Types</strong>.
            As before, to do this you should log into your ItsPlainSailing account, select the
            <strong>Shop</strong> menu option
            and then click on <strong>Merchandise Types</strong> on the left. An example of the type of screen
            you will see is shown below.
