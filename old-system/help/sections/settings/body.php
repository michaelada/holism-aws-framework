    <div class='subsection' id='settings-personal'>
        <h1>
            <a name="settings-personal">Personal Settings</a>
        </h1>
        <p>As the name suggests this is where you can change your personal
            settings. Within this section of settings you can change the
            following:</p>
        <ul>
            <li><span class='highlight title'>Change Password</span> - By
                selecting the <span class='normalbutton save'>Change Password</span> button
                you will
                be prompted to enter your old password and then a new password
                twice. Please note that your password must be a minimum of 8
                characters in length.
            </li>
            <li><span class='highlight title'>Email</span> - While it is
                not expected that you will need to edit your email address it is
                possible to do so here. Please note that if you do change this to a
                new email address then you must use the new email address for all
                future logins to ItsPlainSailing as the old one will no longer
                work. Note also that this does not affect your password, so your
                existing password still applies.
            </li>
            <li><span class='highlight title'>Name</span> - You may edit your
                name.
            </li>
            <li><span class='highlight title'>Contact Number</span> - this is
                where you indicate your contact phone number.
            </li>
            <li><span class='highlight title'>Rows Per Page</span> - When
                displaying large amounts of data in a table, ItsPlainSailing
                doesn't try to show you everything at once, instead it displays
                the information in pages. You can use this setting to configure
                your preferred number of rows per page.
            </li>
            <li><span class='highlight title'>Receive Update Messages</span> -
                from time to time we may need to send emails to our users, if you would not like
                to receive these emails then set this to No.
            </li>
        </ul>
        <p>Remember that if you want to edit any of the fields in your
            personal settings you should simply hover over the field in question with your mouse,
            and then click the Pencil icon on the right. This switches you into
            edit mode, where you can change the value and then to save any changes
            you simply click on the checkbox icon underneath. You can also cancel
            an edit at any time by clicking the small X icon displayed underneath
            the field you are editing.</p>
        <div class="figure-holder">
