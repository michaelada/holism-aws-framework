        <h1>
            <a name="settings-labels">Labels</a>
        </h1>
        <p>In this section of settings you can define a set of Labels for your members. A Label is a
            general form of classification that
            you might use to categorise your members. For example, if you are an equestrian
            club you might define different Labels such as
            Show Jumping, Eventing, Dressage and so forth and then you could assign these Labels to 
            your different
            members. Then you could filter and search your membership database, for
            example to return all members that are interested in Show Jumping (i.e. have the label Show 
            Jumping assigned to them). This is an optional feature which is
            available to use if it suits your club.
            
