    <div class='subsection' id='settings-clubsettings'>
        <h1>
            <a name="settings-clubsettings">Organisation Settings</a>
        </h1>
        <p>The figure below shows an example of the Organisation Settings page.</p>
        <div class="figure-holder">
            <img class="helpfigure" width="845" src="images/settings-club.png"/>
        </div>
        <p class="figure-title">Editing Your Organisations Settings</p>

        <p>Within this page an Administrator can edit specific information
            about your organisation as follows.</p>
        <ul>
            <li><span class='highlight title'>Organisation/ Club Name</span> - You can edit
                the name of your organisation as you would like it to appear to your
                members when they visit your public ItsPlainSailing web page.
            </li>
            <li><span class='highlight title'>Organisation Web Site</span> - If you
                enter your organisation's website address here then we can place a link on your organisation's
                online ItsPlainSailing page which brings people
                automatically back to your organisation's website.
                This link is added automatically when you upload your own Logo under Settings -> Display Settings
                -> Welcome Page.
            </li>
            <li><span class='highlight title'>Facebook Web Address</span> - If you have
                a facebook page then put its web address here and we will add a link
                to it on your organisations online ItsPlainSailing page.
            </li>
            <li><span class='highlight title'>Contact Name</span> - This is the
                name of the contact person within your organisation that we use at
                ItsPlainSailing when we need to let you know about new stuff and
                other communications.
            </li>
            <li><span class='highlight title'>Contact Email</span> - the email
                address of your organisation contact person.
            </li>
            <li><span class='highlight title'>Contact Number</span> - the
                contact phone number for your organisations contact person.
            </li>
            <li><span class='highlight title'>Events Secretary Email</span> -
                the email address of your organisations entries secretary. <span class="ipconly">If members of
                    your organisation enter a competition being run by another club/ branch, and if
                    the competition is configured to do so, then an automatic email
                    will be sent to the Entries Secretary of that branch/ club with the details of the
                    entry made.</span>
            </li>
            <li><span class='highlight title'>Membership Secretary Email(s)</span> -
                the email address(es) of your organisations officials that are automatically notified
                by email when a new membership application or membership renewal is received.
                When entering more than one email address you must separate them using a comma.
            </li>
            <li><span class='highlight title'>Shop/ Merchandise Email(s)</span> -
                the email address(es) of your organisations officials that are automatically notified
                by email when merchandise is ordered.
                When entering more than one email address you must separate them using a comma.
            </li>
            <li><span class='highlight title'>Calendar Booking Email(s)</span> -
                the email address(es) of your organisations officials that are automatically notified
                by email when a calendar booking is made.
                When entering more than one email address you must separate them using a comma.
            </li>
            <li><span class='highlight title'>Restrict Access To Site With Passcode</span> -
                If you only want specific people to be able to access your public ItsPlainSailing page then you
                can set this field to Yes and set a password/ pin code in the <strong>Pass Code To Use</strong>
                field such that people wishing to view your Public Page
                can only do so if they enter the correct password/ pin code.
            </li>

            <li><span class='highlight title'>Abbreviated Name</span> - this is
                read only and is included here for information purposes. It is a
                short abbreviated name for your organisation which we use when
                automatically generating your external web address that people use
                to go to your organisations online web page. In your organisations case your short code is
                <b><span class='clubshortcode'></span> </b> and your organisations
                public online web address is <a target='_blank' class='cluburl' href=''><span
                            class='cluburl'></span> </a></a></li>

            <li><span class='highlight title'>Organisation Type</span> - your organisation type,
                which is not editable, e.g. Pony Club, Rugby Club, Tennis Club, Business, School.
            </li>
            <li><span class='highlight title'>Currency</span> - the currency used on your account.
            </li>

            <li><span class='highlight title'>Subscription Type</span> -
                Indicates the type of subscription chosen for your organisation when you
                activated your account.
            </li>

            <li><span class='highlight title'>Public Web Page</span> - this is
                read only and is included here for information purposes. It displays your organisations
                ItsPlainSailing online web address. This is the one that you should share with your
                members as this is what they will use when submitting applications and paying for entries,
                membership and merchandise. If you have a separate organisation website then you could add
                a button on it called something like 'Online Entries', that when clicked, brings the person to
                this address. Similarly, if you are running an event, you could publish this address on the
                flyer, facebook page or other notices promoting the event so that people know where to go to
                enter.
            </li>

            <li><span class='highlight title'>Make Event Calendar View Public</span> -
                By default the Event Calendar View is only visible to logged in users.
                You can set this to Yes if you would like to make it visible to the public also.
            </li>

            <li><span class='highlight title'>QR Code with Public Page Embedded</span> -
                The QR Code displayed here has your accounts public web address embedded. You can use this as
                a simple way for mobile users to scan the QR Code and bring them straight to your online
                public page for entries/ payments to save them having to type it in on their phones.
            </li>

        </ul>

    </div>

