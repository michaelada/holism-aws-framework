        <h1>
            <a name="intro-activatingaccount">Activating Your Account For
                Payments</a>
        </h1>
        <p>
            If you wish to activate your ItsPlainSailing.com account so that you
            can receive online payments by credit/ debit card then there are 3 steps you
            need to take. To initiate the activation process you should click on
            the <span class='topbutton events'>Activate</span> button along the
            top of your page.
        </p>
        <div class='figure-holder'>
            <img class='helpfigure' width='500' src='images/activate.jpg'/>
        </div>
        <p class='figure-title'>Account Activation Button</p>
        <p><strong>Note</strong></p>
        <p>If you do not see this button then that means that
            your account has already been activated. The figure above highlights
            where the button is located on the page.</p>

        <h4>Activation Steps</h4>
        <p>To activate your account for payments you should do the following</p>
        <table class='instructions'>
            <tr>
                <td class='number'>1</td>
                <td class='details'><span class='highlight title'>Agree To Terms And
                Conditions</span> on the account activation screen you will be
                    presented with the terms and conditions. You should read them fully
                    and if you agree then click the <span class='bluebutton viewentry'>I
                Agree</span> button. Assuming you agree with the terms and
                    conditions you will be automatically brought to step 2.
                </td>
            </tr>
            <tr>
                <td class='number'>2</td>
                <td class='details'><span class='highlight title'>Activate/
                Authorise Your Stripe Account</span> - in order that your organisation can
                    receive credit/ debit card payments it must have a <span class='highlight'>Stripe</span>
                    account and it must be authorised so that ItsPlainSailing.com can
                    use it on your behalf. To initiate this step you should click on
                    the blue <span class='bluebutton viewentry'>Connect with Stripe</span>
                    button shown in the screenshot below.
                    <div class='figure-holder mb-3'>
                        <img class='helpfigure' width='500' src='images/step2-click-blue-button.png'/>
                    </div>

                    When you click this button you will be re-directed to the <strong>stripe.com</strong> website
                    and you should see the screen below, with your email address auto-populated in the email box.
                    <div class='figure-holder mb-3'>
                        <img class='helpfigure' width='500' src='images/step2-stripe-account-enter-email.png'/>
                    </div>
                    <p class='figure-title'>Confirm/ Enter Email Address</p>
                    From this point you will have two different options, one to connect using an existing Stripe Account,
                    the other to create a new Stripe account, each of which is outlined below.
                    <ul class="help">
                        <li><span class='highlight title'>Use Existing Stripe Account</span>
                            - if your organisation already has a Stripe Account then you should make sure
                            the email address for your Stripe account is entered in the email box provided and
                            then you should click continue and enter your associated Stripe password.
                            Assuming you enter the correct credentials
                            then step 2 is automatically completed and ItsPlainSailing.com is
                            authorised to accept credit/ debit card payments into your existing Stripe account
                            on your organisations behalf.
                            <div class='figure-holder'>
                                <img class='helpfigure' width='500' src='images/step2-stripe-account-exists.png'/>
                            </div>
                            <p class='figure-title'>Enter Email and Password for your Existing Stripe Account</p>

                        </li>
                        <li><span class='highlight title'>Create New Stripe Account</span>
                            - Alternatively, if your organisation does not have a Stripe Account then it
                            needs to create one. If this is the case then you will be
                            presented with a series of screens and you will have to go
                            through the Stripe Account Registration process filling out all the fields on
                            this form. To learn more about this click
                            <a href='#payments-striperegistration' class='internal-ref'>Stripe Account
                                Registration</a>. <strong>Note: </strong>
                            you will need your IBAN for this step. Also as part of the registration
                            process you will need to verify your email address and your mobile phone number. To
                            do this Stripe will send you an email with a link included which you must click on
                            to verify that you own the email address, and they will also send a 6 digit code
                            to your phone to verify that it is your mobile number. When you have completed your Stripe
                            registration form you will be automatically brought to step 3. 
                        </li>
                    </ul>
                </td>
            </tr>
            <tr>
                <td class='number'>3</td>
                <td class='details'><span class='highlight title'>Select Payment
                Option</span> - most functionality within ItsPlainSailing.com is
                    available for free however there is a fee to use the Online
                    Payments service . This fee is used by us to pay for the running and ongoing development of
                    the service. Previously we provided several payment options, but now things are simplified to what we refer to
                    as <strong>Standard: Per Transaction</strong> where a small fee is charged whenever a card payment is made.
                    Other than that, there are no setup fees and no ongoing fees, just this handling charge on the card payment.
                    Please select this option to complete the activation process.
                </td>
            </tr>

        </table>


        <h4>Completing Stripe Registration</h4>
        <p>If you create a new Stripe Account for your organisation, you may need to
            also provide proof of your identity. To do this you can proceed in
            one of several ways:


        <ul class="help">
            <li><span class='highlight field label'>Email from Stripe</span> -
                within a couple of days of creating your Stripe account (the time
                seems to vary) you may receive an automatic email from Stripe
                explaining that you still need to Confirm Your Identity, and there
                should be a link in the email which you can use to initiate the
                process with them.
            </li>
            <li><span class='highlight field label'>Log into Stripe</span> -
                alternatively you can log into your Stripe account by going to <a
                        target='_blank' href='https://manage.stripe.com/dashboard'>My
                    Stripe Dashboard</a> and then select <b>Account Settings</b> in
                the drop down list on the Top Right, and you should then select the
                Verification Tab on the right in the window that is
                displayed, and follow the on-screen instructions from Stripe.
            </li>
        </ul>

